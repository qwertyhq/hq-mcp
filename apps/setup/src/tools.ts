import { backendPresence, loadConfig } from '@hq/env';

export interface ToolCounts {
  readonly ro: number;
  readonly rw: number;
  /** Сколько из них ПИШУТ — то есть ради чего предупреждение и существует. */
  readonly writers: number;
}

/**
 * Числа для предупреждения про `rw` берутся из ЖИВОГО реестра, а не из текста.
 *
 * Предупреждение «появятся инструменты, меняющие данные» без числа —
 * это вежливая фраза, которую пролистывают. С числом — это факт, который
 * заставляет остановиться. Но число, вписанное в строку руками, устаревает
 * первым же мутатором, и тогда мастер начинает врать ровно в том месте, где
 * его слушают внимательнее всего. Поэтому оно считается тем же вызовом
 * `Registry.list`, которым транспорт решает, что показать модели.
 *
 * Считать нечем — не повод не спросить: `null` означает «предупреди без
 * чисел». Мастер, упавший на подсчёте украшения, был бы хуже неточного числа.
 *
 * Реестр подтягивается ДИНАМИЧЕСКИМ импортом, и это не стиль. `@hq/runtime`
 * тянет за собой все инструменты разом, и любой сломанный модуль среди них —
 * незавершённая правка, опечатка в экспорте — уронил бы мастер на СТАРТЕ,
 * статическим импортом, ещё до первого вопроса. Настраивать конфигурацию надо
 * ровно тогда, когда что-то не работает; инструмент восстановления, который
 * сам не запускается в сломанном дереве, бесполезен именно в свой час.
 */
export async function countTools(env: Record<string, string>): Promise<ToolCounts | null> {
  try {
    const cfg = loadConfig({ ...env });
    const { buildRuntime } = await import('@hq/runtime');
    const { registry } = buildRuntime(cfg);
    // `backends` обязателен ЗДЕСЬ, а не украшение: без него мастер назвал бы
    // число инструментов полной установки человеку, у которого настроена одна
    // система, — и назвал бы его в том самом месте, где его слушают внимательно
    // (предупреждение про `rw`).
    const backends = backendPresence(cfg);
    const ro = registry.list({ mode: 'ro', profile: cfg.profile, backends });
    const rw = registry.list({ mode: 'rw', profile: cfg.profile, backends });
    return {
      ro: ro.length,
      rw: rw.length,
      writers: rw.filter((def) => def.access === 'rw').length,
    };
  } catch {
    return null;
  }
}
