/**
 * Человек сказал «стоп» — сам или молчанием на вопрос про перезапись.
 *
 * Отдельный тип, потому что это НЕ сбой: мастер обязан выйти без трассы, без
 * слова «error» и, главное, ничего не записав. Отличать намеренный отказ от
 * поломки по тексту сообщения — способ однажды напечатать стек там, где
 * человек просто передумал.
 */
export class SetupAbortedError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'SetupAbortedError';
  }
}
